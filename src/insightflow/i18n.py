def current_language() -> str:
    value = str(st.session_state.get("insightflow_language", "zh-CN"))
    return value if value in LANGUAGES else "zh-CN"


def t(key: str, default: str | None = None, **kwargs: Any) -> str:
    language = current_language()
    value = LOCALES.get(language, {}).get(key, EN.get(key, default or key))
    try:
        return value.format(**kwargs)
    except (KeyError, ValueError):
        return value


def language_name(code: str) -> str:
    return LANGUAGES.get(code, code)


def tr(chinese: str, english: str) -> str:
    """Pick inline copy. Chinese shows only in zh-CN; every other locale reads the English."""
    return chinese if current_language() == "zh-CN" else english
